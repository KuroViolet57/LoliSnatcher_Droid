import 'dart:math';

// Data from https://kaomoji.ru/en/

/// Categories of kaomoji emoticons.
///
/// Each category contains a themed collection of Japanese emoticons (kaomoji).
/// Use [KaomojiData.random] to get a random one.
enum KaomojiCategory {
  /// Happy, cheerful expressions.
  /// Examples: `(*^ω^)`, `(´∀`*)`, `٩(◕‿◕｡)۶`, `(≧◡≦)`
  joy,

  /// Romantic, affectionate expressions with hearts.
  /// Examples: `(*^^*)♡`, `(´｡•ᵕ•｡`)♡`, `♡(◡‿◡)`, `(❤ω❤)`
  love,

  /// Shy, blushing expressions.
  /// Examples: `(⌒_⌒;)`, `(//▽//)`, `(*ﾉ▽ﾉ)`, `(〃▽〃)`
  embarrassment,

  /// Comforting, supportive expressions (usually two characters).
  /// Examples: `(ノ_<。)ヾ(´▽`)`, `(;ω;)ヾ(´∀`*)`, `(っ´ω`)ﾉ(╥ω╥)`
  sympathy,

  /// Annoyed, frustrated expressions.
  /// Examples: `(＃＞＜)`, `(」°ロ°)」`, `(￣ヘ￣)`, `(눈_눈)`
  dissatisfaction,

  /// Angry, furious expressions.
  /// Examples: `(＃`Д´)`, `ψ(`∇´)ψ`, `(ノ°益°)ノ`, `٩(ఠ益ఠ)۶`
  anger,

  /// Sad, crying expressions.
  /// Examples: `(ノ_<。)`, `(;ω;)`, `(T_T)`, `(ಥ﹏ಥ)`
  sadness,

  /// Hurt, injured expressions.
  /// Examples: `~(>_<~)`, `(×_×)`, `(x_x)`, `(ﾒ﹏ﾒ)`
  pain,

  /// Scared, frightened expressions.
  /// Examples: `(ノωヽ)`, `(;;;*_*)`, `Σ(°△°|||)︴`, `Σ(°ロ°)!!!`
  fear,

  /// Shrugging, uncaring expressions.
  /// Examples: `¯\_(ツ)_/¯`, `┐(￣ヘ￣)┌`, `╮(￣_￣)╭`, `ᕕ(ᐛ)ᕗ`
  indifference,

  /// Confused, puzzled expressions.
  /// Examples: `(￣ω￣;)`, `(@_@)`, `(・・)?`, `ლ(ಠ_ಠლ)`
  confusion,

  /// Suspicious, skeptical side-eye expressions.
  /// Examples: `(￢_￢)`, `(→_→)`, `(¬_¬)`, `(←_←)`
  doubt,

  /// Shocked, surprised expressions.
  /// Examples: `Σ(O_O)`, `(o_O)`, `(°ロ°)!`, `∑(O_O;)`
  surprise,

  /// Waving hello/goodbye expressions.
  /// Examples: `(*・ω・)ﾉ`, `(°▽°)/`, `(´▽`)ﾉ`, `(≧▽≦)/`
  greeting,

  /// Hugging expressions with open arms.
  /// Examples: `(づ￣³￣)づ`, `(つ≧▽≦)つ`, `(⊃｡•́‿•̀｡)⊃`, `(っᵔ◡ᵔ)っ`
  hugging,

  /// Winking expressions.
  /// Examples: `(^_~)`, `(^_-)≡☆`, `(^_−)☆`, `(｡•̀ᴗ-)✧`
  winking,

  /// Apologizing, bowing expressions.
  /// Examples: `m(__)m`, `<(__)>`, `(*__)人`, `(シ..)シ`
  apologizing,

  /// Nosebleeding expressions (anime trope for attraction).
  /// Examples: `(*￣ii￣)`, `(￣ﾊ￣*)`, `(^〃^)`, `(￣;;￣)`
  nosebleeding,

  /// Peeking, hiding expressions.
  /// Examples: `|･ω･)`, `|д･)`, `┬┴┬┴┤(･_├┬┴┬┴`, `|ʘ‿ʘ)╯`
  hiding,

  /// Writing expressions with pens.
  /// Examples: `__φ(．．)`, `....φ(・∀・*)`, `(^▽^)ψ__`, `(..)φ__`
  writing,

  /// Running, rushing expressions.
  /// Examples: `☆ﾐ(o*･ω･)ﾉ`, `ε=ε=ε=ε=┌(;￣▽￣)┘`, `ε===(っ≧ω≦)っ`
  running,

  /// Sleeping expressions with zzZ.
  /// Examples: `[(－－)]..zzZ`, `(∪｡∪)｡｡｡zzZ`, `(－ω－)zzZ`
  sleeping,

  /// Cat faces and expressions.
  /// Examples: `(=^･ω･^=)`, `ฅ(•ㅅ•❀)ฅ`, `ʕ•ᴥ•ʔ`, `(Φω Φ)`
  cat,

  /// Bear faces and expressions.
  /// Examples: `ʕ•ᴥ•ʔ`, `(´(ｴ)ˋ)`, `⊂(￣(ｴ)￣)⊃`, `ʕಠᴥಠʔ`
  bear,

  /// Dog faces and expressions.
  /// Examples: `∪･ω･∪`, `V●ᴥ●V`, `U・ᴥ・U`, `U^ｪ^U`
  dog,

  /// Rabbit faces with long ears.
  /// Examples: `/(≧x≦)＼`, `/(･×･)＼`, `૮˶ᵔᵕᵔ˶ა`, `/(˃ᆺ˂)＼`
  rabbit,

  /// Pig faces with snouts.
  /// Examples: `(´(00)ˋ)`, `(￣(ω)￣)`, `(￣(00)￣)`, `(ˆ(oo)ˆ)`
  pig,

  /// Bird faces with beaks.
  /// Examples: `(￣Θ￣)`, `(`･Θ･´)`, `(・Θ・)`, `(･Θ･)`
  bird,

  /// Fish expressions.
  /// Examples: `<・)))><`, `>°))))彡`, `≧(°°)≦`, `ζ°)))彡`
  fish,

  /// Spider expressions with multiple legs.
  /// Examples: `/╲/\╭(ఠఠ益ఠఠ)╮/\╱\`, `/╲/\(•̀ω•́)/\╱\`
  spider,

  /// Two or more friends together.
  /// Examples: `ヾ(・ω・)メ(・ω・)ノ`, `(*^ω^)人(^ω^*)`, `(☞°ヮ°)☞☜(°ヮ°☜)`
  friends,

  /// Fighting, attacking expressions.
  /// Examples: `ヽ(･∀･)ﾉ_θ彡☆Σ(ノ`Д´)ノ`, `(╯°Д°)╯︵/(.□.\)`
  enemies,

  /// Weapons like swords, guns, bows.
  /// Examples: `(・∀・)・・・--------☆`, `(ﾒ`ﾛ´)︻デ═一`, `―(T_T)→`
  weapons,

  /// Magic casting expressions with sparkles.
  /// Examples: `╰(͡°˜ʖ͡°)つ──☆*:・ﾟ`, `(⊃｡•́‿•̀｡)⊃━✿✿✿✿✿✿`
  magic,

  /// Food and eating expressions.
  /// Examples: `(っ˘ڡ˘ς)`, `(˘▽˘)っ♨`, `(￣﹃￣)`, `(๑ᵔ⤙ᵔ๑)`
  food,

  /// Dancing and singing expressions.
  /// Examples: `♪♪♪ヽ(ˇ∀ˇ)ゞ`, `ヘ(￣ω￣ヘ)`, `♬♫♪◖(●o●)◗♪♫♬`
  music,

  /// Gaming expressions.
  /// Examples: `(^^)p_____|o____q(^^)`, `(˙ω˙)🎮(˙∀˙)🎮`
  games,

  /// Lenny and similar meme faces.
  /// Examples: `(͡°˜ʖ͡°)`, `(ಠ_ಠ)`, `(͡ᵔ˜ʖ͡ᵔ)`, `(ಥʖ̯ಥ)`
  faces,

  /// Miscellaneous special kaomojis.
  /// Examples: `(╯°益°)╯彡┻━┻`, `┬─┬ノ(º_ºノ)`, `(⌐■_■)`, `_(:3」∠)_`
  special,
}

