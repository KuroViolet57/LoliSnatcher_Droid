    ('character', 'Characters'),
    ('tag', 'Tags'),
    ('language', 'Languages'),
    ('category', 'Categories'),
  ];

  @override
  List<MetaTag> availableMetaTags() => [
    StringMetaTag(name: 'Artist', keyName: 'artist'),
    StringMetaTag(name: 'Group', keyName: 'group'),
    StringMetaTag(name: 'Series', keyName: 'parody'),
    StringMetaTag(name: 'Character', keyName: 'character'),
    StringMetaTag(name: 'Language', keyName: 'language'),
    StringMetaTag(name: 'Category', keyName: 'category'),
  ];

  @override
  Future<List<Tag>> tagsForListingItem(BooruItem item) async {
    final String id = item.serverId ?? '';
    if (id.isEmpty) return const [];
    final response = await DioNetwork.get(makePostURL(id), headers: getHeaders());
    if (response.statusCode != 200) return const [];
    return _tagsFrom(parse(response.data.toString()));
  }

  // ── detail + reader ───────────────────────────────────────────────────

  @override
  Future<({BooruItem? item, bool failed, String? error})> loadItem({
    required BooruItem item,
    dynamic cancelToken,
    bool withCapcthaCheck = false,
  }) async {
    final String id = item.serverId ?? '';
    if (id.isEmpty) return (item: null, failed: true, error: 'no gallery id');
    try {
      final article = await DioNetwork.get(makePostURL(id), headers: getHeaders());
      if (article.statusCode != 200) {
        return (item: null, failed: true, error: 'status ${article.statusCode} on the gallery page');
      }
      final dom.Document doc = parse(article.data.toString());
      final List<Tag> tags = _tagsFrom(doc);
      if (tags.isNotEmpty) item.tagsList = tags;
      final String title = doc.querySelector('h1')?.text.trim() ?? '';
      if (title.isNotEmpty) item.description = title;

      final viewer = await DioNetwork.get('$_site/viewer?articleId=$id&page=1', headers: getHeaders());
      if (viewer.statusCode != 200) {
        return (item: null, failed: true, error: 'status ${viewer.statusCode} on the viewer');
      }
      final List<String> urls = pageUrlsFrom(id, viewer.data.toString());
      if (urls.isEmpty) return (item: null, failed: true, error: 'the viewer lists no pages');

      final List<BooruItem> pages = [
        for (int i = 0; i < urls.length; i++)
          BooruItem(
            fileURL: urls[i],
            sampleURL: urls[i],
            thumbnailURL: '$cdn/$id/thumbnails/${i + 1}.webp',
            tagsList: const [],
            postURL: makePostURL(id),
          ),
      ];
      ReaderHandler.instance.registerBook(item, pages);
      item.fileCountHint.value = pages.length;
      return (item: item, failed: false, error: null);
    } catch (e) {
      return (item: null, failed: true, error: e.toString());
    }
  }

  // ── generated Related / Recommended ───────────────────────────────────

  Future<BooruItem?> _sourceItem(String id) async {
    try {
      final response = await DioNetwork.get(makePostURL(id), headers: getHeaders());
      if (response.statusCode != 200) return null;
      return _itemFromArticlePage(id, response.data.toString());
    } catch (_) {
      return null;
    }
  }

  Future<List<BooruItem>> _candidatesFor(BooruItem source) async {
    final List<String> queries = [
      for (final t in source.tagsList.where((t) => t.tagType != TagType.meta).take(4)) t.fullString.replaceAll('_', ' '),
      DoujinRecommendationEngine.baseTitle(
        (source.description ?? '').split('\n').firstWhere((l) => l.trim().isNotEmpty, orElse: () => ''),
      ),
    ].where((q) => q.trim().length > 2).toList();

    final List<BooruItem> out = [];
    final Set<String> seen = {source.postURL};
    for (final query in queries) {
      try {
        final response = await DioNetwork.get(
          '$_site/articles/search?keyword=${Uri.encodeQueryComponent(query)}&page=1',
          headers: getHeaders(),
        );
        for (final item in _itemsFromListing(response.data.toString())) {
          if (seen.add(item.postURL)) out.add(item);
        }
      } catch (_) {}
    }
    return out;
  }

  Future<void> _fillTags(List<BooruItem> items, {int limit = 8}) async {
    for (final item in items.take(limit)) {
      if (item.tagsList.length > 1) continue;
      try {
        final response = await DioNetwork.get(item.postURL, headers: getHeaders());
        item.tagsList = _tagsFrom(parse(response.data.toString()));
      } catch (_) {}
    }
  }

  Future<List<BooruItem>> _fetchRelated(String id) async {
    final source = await _sourceItem(id);
    if (source == null) return [];
    return DoujinRecommendationEngine.related(source, await _candidatesFor(source));
  }

  Future<List<BooruItem>> _fetchRecommended(String id) async {
    final source = await _sourceItem(id);
    if (source == null) return [];
    final candidates = await _candidatesFor(source);
    await _fillTags(candidates);
    String? artist;
    for (final tag in source.tagsList) {
      if (tag.tagType == TagType.artist) {
        artist = tag.fullString;
        break;
      }
    }
    return DoujinRecommendationEngine.rank(
      source,
      candidates,
      count: limit,
      sourceArtist: (artist?.isEmpty ?? true) ? null : artist,
    );
  }

  @override
  String? relatedVersionsQuery(BooruItem item) {
    final String id = item.serverId ?? '';
    return id.isEmpty ? null : 'related:$id';
  }
}
