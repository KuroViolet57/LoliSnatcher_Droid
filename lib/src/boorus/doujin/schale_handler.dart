/// niyaniya.moe — the Schale Network JSON API.
///
/// Clean and fully documented by observation:
///   `GET /books?s=<query>&page=N`   search / browse (`s`, not `search`)
///   `GET /books/popular?page=N`     the popular shelf
///   `GET /books/detail/{id}/{key}`  tags, page list, stats
///   `GET /books/favorites`          the signed-in account's favourites
///
/// Images live on two CDNs: `thumbnails.base` and a `fallback` host carrying
/// the identical path. Every URL this handler builds prefers the primary and
/// records the fallback, because the primary does intermittently fail.
///
/// Related is the site's own `similar` list (clearance-gated); Recommended is
/// generated by [DoujinRecommendationEngine] from titles and tags.
class SchaleHandler extends BooruHandler with DoujinListingTagBackfill, DoujinNamespacedTags {
  SchaleHandler(super.booru, super.limit);

  static const String _api = 'https://api.schale.network';
  static const String defaultSite = 'https://niyaniya.moe';

  /// The mirror as configured, without a trailing slash.
  String get _configuredSite {
    final String configured = booru.baseURL?.trim() ?? '';
    if (configured.isEmpty) return defaultSite;
    return configured.endsWith('/') ? configured.substring(0, configured.length - 1) : configured;
  }

  /// Live domain per configured base, learned from the site's own redirect.
  static final Map<String, String> _resolvedDomains = {};

  /// The mirror actually in use: the configured base until [resolveDomain]
  /// has run, the redirect target after. Referer and Origin derive from this,
  /// so a base of shupogaki.moe no longer sends headers naming niyaniya. The
  /// API host is shared across mirrors and never changes.
  String get _site => _resolvedDomains[_configuredSite] ?? _configuredSite;

  /// Koharu's `getDomain()`: a non-following GET to the base URL, reading the
  /// `Location` host. Cached per base; a base that does not redirect resolves
  /// to itself.
  Future<String> resolveDomain() async {
    final String base = _configuredSite;
    final String? cached = _resolvedDomains[base];
    if (cached != null) return cached;
    String resolved = base;
    try {
      final response = await DioNetwork.get(
        base,
        headers: {'User-Agent': SchaleClearanceHandler.reducedChromeUserAgent(Tools.browserUserAgent)},
        options: Options(followRedirects: false, validateStatus: (_) => true),
      );
      final String host = Uri.tryParse(response.headers.value('location') ?? '')?.host ?? '';
      if (host.isNotEmpty) resolved = 'https://$host';
    } catch (_) {
      // Unreachable base: keep what was configured.
    }
    _resolvedDomains[base] = resolved;
    return resolved;
  }

