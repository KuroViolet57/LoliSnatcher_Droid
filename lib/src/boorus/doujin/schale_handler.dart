  /// Suggestions come from the tag names attached to search results, which is
  /// the only tag surface the API exposes.
  @override
  Future<Either<ResponseError, List<TagSuggestion>>> getTagSuggestions(
    String input, {
    dynamic cancelToken,
  }) async {
    final String query = input.trim();
    if (query.isEmpty) return const Right([]);
    try {
      final response = await DioNetwork.get(
        '$_api/books?s=${Uri.encodeQueryComponent(query)}&page=1',
        headers: getHeaders(),
      );
      final data = _json(response.data);
      if (data is! Map) return const Right([]);
      final Set<String> names = {};
      for (final row in data['entries'] as List? ?? []) {
        if (row is Map && row['title'] != null) {
          for (final word in DoujinRecommendationEngine.titleTokens(row['title'].toString())) {
            if (word.startsWith(query.toLowerCase())) names.add(word);
          }
        }
      }
      return Right([
        for (final n in names.take(20)) TagSuggestion(tag: n, type: TagType.none),
      ]);
    } catch (e) {
      return Left(ResponseError(message: e.toString()));
    }
  }
