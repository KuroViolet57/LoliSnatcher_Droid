  /// The API rejects requests that don't look like they came from the site.
  ///
  /// The user agent matters beyond looking right. The clearance token is minted
  /// inside the challenge webview, which presents a plain Chrome UA because the
  /// site refuses to render a Turnstile for anything containing `wv`. Sending a
  /// DIFFERENT user agent when spending that token asks the API to honour a
  /// clearance earned by what looks like another client. Both halves now use
  /// the same string.
  @override
  Map<String, String> getHeaders() => {
    ...super.getHeaders(),
    // The same reduced Chrome string the solver window presents, so a token
    // earned there is spent by what looks like the same client.
    'User-Agent': SchaleClearanceHandler.reducedChromeUserAgent(Tools.browserUserAgent),
    'Referer': '$_site/',
    'Origin': _site,
    'Accept': 'application/json',
    if (booru.apiKey?.isNotEmpty == true) 'Authorization': 'Bearer ${booru.apiKey}',
  };

  static dynamic _json(dynamic data) => data is String ? jsonDecode(data) : data;

  /// niyaniya keeps its images on erocdn mirrors, which serve them without a
  /// referer today. Sending the one a browser would send anyway costs nothing
