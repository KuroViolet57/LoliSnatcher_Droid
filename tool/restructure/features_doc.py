#!/usr/bin/env python3
"""Writes docs/FEATURES.md from the subsystem maps (docs/superpowers/specs/1.0-map/*.json).

    python tool/restructure/features_doc.py

The catalogue lists every user-visible feature the 1.0 restructure had to keep,
with where to find it, the settings it reads, where its data lives and whether
backups carry it. File paths are translated to the 1.0 layout.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MAP = os.path.join(ROOT, 'docs', 'superpowers', 'specs', '1.0-map')
MAPPING = json.load(open(os.path.join(ROOT, 'tool', 'restructure', 'mapping_m1.json'), encoding='utf-8'))
TITLES = {
    'shell': 'App shell: startup, home, drawers, theme, lock',
    'settings': 'Settings',
    'feed': 'The feed: tabs content, search, query editors, thumbnails',
    'tabs_drawers': 'Tab manager, side drawers, history, collections',
    'viewer': 'The viewer: pictures, videos, info sheet, toolbar',
    'doujin': 'Doujin: sources, reader, detail page, library',
    'tags_ml': 'Tags and the on-device models / recommendations',
    'persistence_downloads_diag': 'Storage, backup, sync, downloads, diagnostics',
    'sources': 'Sources (sites) and their pages',
}
ORDER = ['shell', 'feed', 'tabs_drawers', 'viewer', 'doujin', 'tags_ml', 'sources', 'settings', 'persistence_downloads_diag']


def new_path(p):
    p = p.strip()
    return MAPPING.get(p, p).replace('lib/', '', 1)


def esc(s):
    return (s or '').replace('|', '\\|').replace('\n', ' ').replace('&gt;', '>').replace('-&gt;', '->')


def main():
    out = ['# Features', '',
           'Every user-visible feature and automatic behaviour of LoliSnatcher 1.0, as mapped from the code',
           'for the 1.0 restructure (October 2026). "Where" is the path in the app; "Settings" are the',
           '`settings.json` keys it reads; "Data" is where it keeps what it stores; "Backup" says whether',
           'Settings -> Backup & restore carries it. Generated by `tool/restructure/features_doc.py`.', '']
    total = 0
    for key in ORDER:
        path = os.path.join(MAP, f'{key}.json')
        if not os.path.exists(path):
            continue
        r = json.load(open(path, encoding='utf-8'))
        feats = r['features']
        total += len(feats)
        out += [f'## {TITLES.get(key, key)} ({len(feats)})', '',
                '| # | Feature | Where | What it does | Settings | Data | Backup |',
                '|---|---|---|---|---|---|---|']
        for i, f in enumerate(feats, 1):
            out.append('| {} | {} | {} | {} | {} | {} | {} |'.format(
                i, esc(f['name']), esc(f.get('navPath')), esc(f.get('what')),
                esc(', '.join(f.get('settingsKeys') or [])), esc(f.get('storedIn')), esc(f.get('inBackup'))))
        out.append('')
    out.insert(6, f'{total} entries.\n')
    open(os.path.join(ROOT, 'docs', 'FEATURES.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('features:', total)


if __name__ == '__main__':
    main()
